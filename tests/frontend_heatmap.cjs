const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = {window:{}, safe:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;'), fmt:n=>String(n)};
vm.createContext(context);
vm.runInContext(fs.readFileSync('frontend/history-heatmap.js','utf8'),context);
const render=context.window.renderHistoryHeatmap;
const points=[];
for(let year=2024;year<=2025;year++)for(let month=1;month<=12;month++)points.push({period:`${year}-${String(month).padStart(2,'0')}`,value:month===2&&year===2025?null:month*10});
points.push({period:'2026-01',value:1000});
const series={frequency:'monthly',start:2024,end:2026,geography:'Test <country>',unit:'cases',source:'WHO',source_url:'https://www.who.int/',retrieved_at:'2026-10-22',points};
const chart=render(series);
assert.equal((chart.match(/role="img"/g)||[]).length,12);
assert.ok(chart.includes('Typical reporting pattern by month'));
assert.ok(chart.includes('Test &lt;country> · Feb · median 20 cases from 1 reported period'));
assert.ok(chart.includes('Missing reporting periods are excluded, not treated as zero'));
assert.ok(chart.includes('does not estimate seasonality or forecast an outbreak'));
assert.ok(!chart.includes('Reported-case intensity through time'));
assert.equal(render({...series,frequency:'outbreak'}),'');
assert.equal(render({...series,frequency:'annual'}),'');
assert.equal(render({...series,points:points.slice(0,12)}),'');
console.log('Seasonal profile checks passed: medians, missing-period handling, escaping and eligibility.');
